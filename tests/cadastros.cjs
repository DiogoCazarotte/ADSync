const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium } = require('playwright');
// Fixed endpoints: this suite never targets the Supabase application.
const origin = 'http://127.0.0.1:5126';
const api = 'http://127.0.0.1:5100';
const credentials = JSON.parse(fs.readFileSync('.local-demo/cadastros/credentials.json', 'utf8').replace(/^\uFEFF/, ''));
(async () => {
    const runtime = await (await fetch(api + '/api/runtime')).json();
    assert.equal(runtime.readOnly, false);
    const browser = await chromium.launch({headless:true, executablePath:process.env.CHROMIUM_PATH || 'C:/Program Files/BraveSoftware/Brave-Browser/Application/brave.exe'});
    try {
        const page = await browser.newPage();
        const errors = [];
        page.on('pageerror', e => errors.push(e.message));
        await page.goto(origin);
        await page.getByLabel('E-mail', {exact:true}).fill(credentials.Email);
        await page.getByLabel('Senha', {exact:true}).fill(credentials.Password);
        await page.getByRole('button', {name:'Entrar', exact:true}).click();
        const cadastros = page.getByRole('button', {name:'Cadastros', exact:true});
        await cadastros.waitFor();
        await page.waitForFunction(() => [...document.querySelectorAll('button')].some(b => b.textContent === 'Cadastros' && !b.disabled));
        await cadastros.click();
        const equipment = page.locator('section').filter({has:page.getByRole('heading', {name:'Equipamentos', exact:true})});
        const parts = page.locator('section').filter({has:page.getByRole('heading', {name:'Peças e estoque', exact:true})});
        const causes = page.locator('section').filter({has:page.getByRole('heading', {name:'Causas de falha', exact:true})});
        const suffix = Date.now().toString();
        const name = 'Teste equipamento ' + suffix;
        await equipment.getByLabel('Nome', {exact:true}).fill(name);
        await equipment.getByLabel('Código de patrimônio').fill('T-' + suffix);
        await equipment.getByLabel('Setor').fill('Testes');
        await equipment.getByRole('button', {name:'Salvar equipamento', exact:true}).click();
        let card = equipment.locator('article').filter({hasText:name});
        await card.waitFor();
        await card.getByRole('button', {name:'Editar equipamento'}).click();
        await equipment.getByLabel('Nome', {exact:true}).fill(name + ' editado');
        await equipment.getByRole('button', {name:'Salvar equipamento', exact:true}).click();
        await card.getByRole('heading', {name:name + ' editado', exact:true}).waitFor();
        await card.getByRole('button', {name:'Inativar', exact:true}).click();
        await card.getByRole('button', {name:'Ativar', exact:true}).waitFor();
        await card.getByRole('button', {name:'Ativar', exact:true}).click();
        await card.getByRole('button', {name:'Inativar', exact:true}).waitFor();
        console.log('PASS: criar, editar, inativar e ativar equipamento.');
        await parts.getByLabel('Código', {exact:true}).fill('P-' + suffix);
        await parts.getByLabel('Nome', {exact:true}).fill('Peça ' + suffix);
        await parts.getByLabel('Quantidade inicial').fill('3');
        await parts.getByRole('button', {name:'Salvar peça', exact:true}).click();
        card = parts.locator('article').filter({hasText:'P-' + suffix});
        await card.waitFor();
        await card.getByRole('button', {name:'Editar peça'}).click();
        await parts.getByLabel('Nome', {exact:true}).fill('Peça editada ' + suffix);
        await parts.getByRole('button', {name:'Salvar peça', exact:true}).click();
        await card.getByRole('heading', {name:'P-' + suffix + ' • Peça editada ' + suffix, exact:true}).waitFor();
        await card.getByRole('button', {name:'Entrada de estoque'}).click();
        await card.getByLabel('Quantidade recebida').fill('2');
        await card.getByRole('button', {name:'Confirmar entrada'}).click();
        await card.getByText('5 unidade(s)', {exact:true}).waitFor();
        console.log('PASS: criar e editar peça; entrada soma ao estoque (3 + 2 = 5).');
        const cause = 'Causa ' + suffix;
        await causes.getByLabel('Descrição', {exact:true}).fill(cause);
        await causes.getByRole('button', {name:'Salvar causa', exact:true}).click();
        card = causes.locator('article').filter({hasText:cause});
        await card.waitFor();
        await card.getByRole('button', {name:'Editar causa'}).click();
        await causes.getByLabel('Descrição', {exact:true}).fill(cause + ' editada');
        await causes.getByRole('button', {name:'Salvar causa', exact:true}).click();
        await card.getByRole('heading', {name:cause + ' editada', exact:true}).waitFor();
        await card.getByRole('button', {name:'Inativar', exact:true}).click();
        await card.getByRole('button', {name:'Ativar', exact:true}).waitFor();
        await card.getByRole('button', {name:'Ativar', exact:true}).click();
        await card.getByRole('button', {name:'Inativar', exact:true}).waitFor();
        console.log('PASS: criar, editar, inativar e ativar causa de falha.');
        assert.deepEqual(errors, []);
    } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
