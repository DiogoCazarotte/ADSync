const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium } = require('playwright');
const api = 'http://127.0.0.1:5100';
const origin = 'http://127.0.0.1:5126';
const credentials = JSON.parse(fs.readFileSync('.local-demo/cadastros/credentials.json', 'utf8').replace(/^\uFEFF/, ''));
(async () => {
    assert.equal((await (await fetch(api + '/api/runtime')).json()).readOnly, false);
    const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH || 'C:/Program Files/BraveSoftware/Brave-Browser/Application/brave.exe' });
    const senha = 'Test!9a' + Date.now();
    const email = 'usuario-' + Date.now() + '@example.test';
    try {
        const page = await browser.newPage();
        await page.goto(origin);
        await page.getByLabel('E-mail', {exact:true}).fill(credentials.Email);
        await page.getByLabel('Senha', {exact:true}).fill(credentials.Password);
        await page.getByRole('button', {name:'Entrar', exact:true}).click();
        await page.getByRole('button', {name:'Usuários', exact:true}).click();
        await page.getByLabel('Nome', {exact:true}).fill('Usuário teste');
        await page.getByLabel('E-mail do usuário').fill(email);
        await page.getByLabel('Senha inicial').fill(senha);
        await page.getByRole('button', {name:'Salvar usuário', exact:true}).click();
        const card = page.locator('article').filter({hasText:email});
        await card.waitFor();
        const login = async (email, senha) => fetch(api + '/api/auth/login', {method:'POST', headers:{'Content-Type':'application/json'}, body:JSON.stringify({email,senha})});
        const admin = await (await login(credentials.Email, credentials.Password)).json();
        const request = (path, method = 'GET', body, token = admin.token) => fetch(api + path, {method, headers:{Authorization:'Bearer ' + token,'Content-Type':'application/json'}, body:body ? JSON.stringify(body) : undefined});
        const operator = await (await login(email, senha)).json();
        assert.equal((await request('/api/usuarios','GET',null,operator.token)).status,403);
        const all = await (await request('/api/usuarios?incluirInativos=true')).json();
        const self = all.find(u => u.email === credentials.Email);
        assert.equal((await request(`/api/usuarios/${self.id}/situacao`, 'PUT', {ativo:false})).status,409);
        assert.equal((await request(`/api/usuarios/${self.id}`, 'PUT', {nome:self.nome,email:self.email,tipoUsuario:0})).status,409);
        assert.equal((await request('/api/usuarios', 'POST', {nome:'Duplicado',email,senha,tipoUsuario:0})).status,409);
        await card.getByRole('button', {name:'Editar usuário'}).click();
        await page.getByLabel('Nome', {exact:true}).fill('Usuário editado');
        await page.getByLabel('Perfil', {exact:true}).selectOption('Tecnico');
        await page.getByRole('button', {name:'Salvar usuário', exact:true}).click();
        await card.getByRole('heading', {name:'Usuário editado',exact:true}).waitFor();
        assert.equal((await request('/api/ordensservico','GET',null,operator.token)).status,401);
        const tecnico = await (await login(email, senha)).json();
        assert.deepEqual(tecnico.papeis, ['Tecnico']);
        await card.getByRole('button', {name:'Desativar usuário'}).click();
        await card.getByRole('button', {name:'Ativar usuário'}).waitFor();
        assert.equal((await request('/api/ordensservico','GET',null,tecnico.token)).status,401);
        assert.equal((await login(email, senha)).status,401);
        await card.getByRole('button', {name:'Ativar usuário'}).click();
        await card.getByRole('button', {name:'Desativar usuário'}).waitFor();
        assert.equal((await login(email, senha)).status,200);
        console.log('PASS: cadastro e edição pela interface; perfis; e-mail duplicado; proteção da própria conta; invalidação de sessão; desativação e reativação.');
    } finally { await browser.close(); }
})().catch(e => { console.error(e.message); process.exitCode = 1; });
